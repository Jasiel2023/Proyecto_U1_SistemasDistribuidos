-- Esquema inicial del microservicio de autenticacion.
-- Los nombres coinciden con las anotaciones @Table/@Column de las entidades.

CREATE TABLE cuenta (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname VARCHAR(100) NOT NULL UNIQUE,
    clave_cifrada VARCHAR(255) NOT NULL,
    esta_activa BOOLEAN NOT NULL
);

CREATE TABLE sesion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(512) NOT NULL UNIQUE,
    fecha_emision TIMESTAMP NOT NULL,
    fecha_expiracion TIMESTAMP NOT NULL,
    estado_token VARCHAR(20) NOT NULL,
    cuenta_id INTEGER NOT NULL UNIQUE,
    CONSTRAINT fk_sesion_cuenta FOREIGN KEY (cuenta_id) REFERENCES cuenta (id) ON DELETE CASCADE
);

CREATE INDEX idx_sesion_cuenta ON sesion (cuenta_id);
CREATE INDEX idx_sesion_estado ON sesion (estado_token);
