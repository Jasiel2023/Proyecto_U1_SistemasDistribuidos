CREATE TABLE votaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ABIERTA',
    fecha_inicio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_fin TIMESTAMPTZ,
    CONSTRAINT ck_votaciones_estado
        CHECK (estado IN ('ABIERTA', 'CERRADA')),
    CONSTRAINT ck_votaciones_periodo
        CHECK (fecha_fin IS NULL OR fecha_fin > fecha_inicio)
);

CREATE TABLE opciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    votacion_id BIGINT NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_opciones_votacion
        FOREIGN KEY (votacion_id) REFERENCES votaciones (id),
    CONSTRAINT uq_opciones_id_votacion
        UNIQUE (id, votacion_id)
);

CREATE TABLE votos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    votacion_id BIGINT NOT NULL,
    opcion_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    emitido_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_votos_votacion
        FOREIGN KEY (votacion_id) REFERENCES votaciones (id),
    CONSTRAINT fk_votos_opcion_de_votacion
        FOREIGN KEY (opcion_id, votacion_id)
        REFERENCES opciones (id, votacion_id),
    CONSTRAINT ck_votos_usuario_positivo
        CHECK (usuario_id > 0),
    CONSTRAINT uq_votos_usuario_por_votacion
        UNIQUE (votacion_id, usuario_id)
);

CREATE INDEX idx_opciones_votacion_id
    ON opciones (votacion_id);

CREATE INDEX idx_votos_votacion_id
    ON votos (votacion_id);

CREATE INDEX idx_votos_opcion_id
    ON votos (opcion_id);

CREATE INDEX idx_votos_usuario_id
    ON votos (usuario_id);
